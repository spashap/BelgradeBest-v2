"""subset-fonts.py — builds the site's trimmed "latin-ext" font files and src/styles/fonts.css.

Why (2026-11-23 speed check): @fontsource's latin-ext files (Inter 84 KB, Newsreader
36 KB) download on every page that shows one Serbian or Czech letter (č, š, ě ...),
at top priority, competing with the page itself on phones. The site uses about 20
of their ~600 glyphs. This keeps the same fonts and look, and ships only the Central
European letters (Serbian/Croatian, Czech, Slovak, Polish, Hungarian, Romanian,
Turkish, macron vowels): about 70 code points.

Run after upgrading @fontsource-variable/* or when a new language needs letters:
    python scripts/subset-fonts.py
Needs fontTools + brotli (pip install fonttools brotli). Not deployed (scripts/).
Writes src/assets/fonts/*-ext-bb-wght.woff2 and src/styles/fonts.css (generated;
do not edit by hand). The build then fingerprints the files under /_astro/.
"""
from pathlib import Path
from fontTools import subset

ROOT = Path(__file__).resolve().parent.parent
NM = ROOT / "node_modules" / "@fontsource-variable"
OUT_DIR = ROOT / "src" / "assets" / "fonts"
CSS = ROOT / "src" / "styles" / "fonts.css"

LETTERS = (
    "ČčĆćĐđŠšŽž"          # Serbian / Croatian / Bosnian / Slovenian
    "ĚěŘřŮůŇňŤťĎď"        # Czech (+ Slovak ň ť ď)
    "ĽľĹĺŔŕ"              # Slovak
    "ĄąĘęŁłŃńŚśŹźŻż"      # Polish
    "ŐőŰű"                # Hungarian
    "ĂăȘșȚțŞşŢţ"          # Romanian (comma and cedilla forms)
    "Ğğİ"                 # Turkish (ı, ş are covered above or by latin)
    "ĀāĒēĪīŌōŪū"          # macron vowels (Japanese romanisation: Ōsaka)
)
CODEPOINTS = sorted({ord(c) for c in LETTERS})
RANGE = ",".join(f"U+{cp:04X}" for cp in CODEPOINTS)

# Fontsource's own ranges for the subsets we keep untouched.
LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD"
CYRILLIC = "U+0301,U+0400-045F,U+0490-0491,U+04B0-04B1,U+2116"

FONTS = [
    # family, package, weight range, keep cyrillic?
    ("Inter Variable", "inter", "100 900", True),
    ("Newsreader Variable", "newsreader", "200 800", False),
]


def subset_font(pkg: str) -> Path:
    src = NM / pkg / "files" / f"{pkg}-latin-ext-wght-normal.woff2"
    dst = OUT_DIR / f"{pkg}-ext-bb-wght.woff2"
    opts = subset.Options()
    opts.flavor = "woff2"
    opts.layout_features = ["*"]      # keep kerning and mark positioning for the accents
    opts.name_IDs = ["*"]
    opts.notdef_outline = True
    opts.hinting = False
    font = subset.load_font(str(src), opts)
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=CODEPOINTS)
    sub.subset(font)
    subset.save_font(font, str(dst), opts)
    print(f"{src.name} {src.stat().st_size // 1024} KB -> {dst.name} {dst.stat().st_size // 1024} KB")
    return dst


def face(family: str, url: str, weight: str, urange: str) -> str:
    return (
        "@font-face {\n"
        f"  font-family: '{family}';\n"
        "  font-style: normal;\n"
        "  font-display: swap;\n"
        f"  font-weight: {weight};\n"
        f"  src: url(\"{url}\") format('woff2-variations');\n"
        f"  unicode-range: {urange};\n"
        "}\n"
    )


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    parts = [
        "/* GENERATED by scripts/subset-fonts.py — do not edit by hand.\n"
        "   Replaces the full @fontsource-variable imports: Latin as published,\n"
        "   Cyrillic (Inter only; glossary pages), and a trimmed Central European\n"
        "   'ext-bb' file instead of the full latin-ext. Glyphs outside these ranges\n"
        "   fall back to the system font. */\n"
    ]
    for family, pkg, weight, cyr in FONTS:
        subset_font(pkg)
        nm = f"../../node_modules/@fontsource-variable/{pkg}/files"
        if cyr:
            parts.append(face(family, f"{nm}/{pkg}-cyrillic-wght-normal.woff2", weight, CYRILLIC))
        parts.append(face(family, f"../assets/fonts/{pkg}-ext-bb-wght.woff2", weight, RANGE))
        parts.append(face(family, f"{nm}/{pkg}-latin-wght-normal.woff2", weight, LATIN))
    CSS.write_text("\n".join(parts), encoding="utf-8", newline="\n")
    print(f"wrote {CSS.relative_to(ROOT)} ({len(CODEPOINTS)} extra letters)")


if __name__ == "__main__":
    main()
